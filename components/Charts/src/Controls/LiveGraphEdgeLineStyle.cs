namespace JPSoftworks.DesktopToolkit.Charts;

/// <summary>
/// Specifies how the upper edge of a live area series is drawn.
/// </summary>
public enum LiveGraphEdgeLineStyle
{
    /// <summary>Hides the upper edge.</summary>
    None,

    /// <summary>Draws a continuous upper edge.</summary>
    Solid,

    /// <summary>Draws a dashed upper edge.</summary>
    Dashed,
}
