namespace JPSoftworks.DesktopToolkit.Controls;

/// <summary>Specifies the position of the filter field in an open flyout.</summary>
public enum FilterBoxPlacement
{
    /// <summary>Places the field at the opening edge nearest the trigger.</summary>
    Auto,

    /// <summary>Places the field above the items.</summary>
    Top,

    /// <summary>Places the field below the items.</summary>
    Bottom,
}
